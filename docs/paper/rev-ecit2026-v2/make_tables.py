#!/usr/bin/env python3
"""Generate the tables and number macros of the REV-ECIT 2026 paper (v2).

Two sources, each optional so the paper builds while the other is missing:

  pooled_comparison.json  (./isd-exp pool comparison over the c1 run)
      -> tab_judge.tex: LLM judge scores (mean ± SD across scenarios) + tokens,
         the proposed system against the six ISD-Agent-Bench agents
      -> macros for the prose, and the spread between the three LLM judges read
         from each scenario's comparison_report.json

  a web-app run dir  (--case-dir; default case/run/, the copy of
                     alignmentgraph-isd/.agisd-server-data/programs/<p>/runs/<r> kept with the paper)
      -> macros for the deployment case: artifact counts, C2-C4 coverage,
         objectives that close the triad, the violation ledger, tokens

Statistics are the pooling's, not recomputed here: paired Wilcoxon per scenario,
Holm within one score, failure = 0. A baseline cell is starred when its
difference from the proposed system has p_holm < ALPHA.

Run with the experiment's interpreter (stdlib only):
  experiments/.venv/bin/python docs/paper/rev-ecit2026-v2/make_tables.py --case-dir <run dir>
"""
from __future__ import annotations

import argparse
import ast
import json
import math
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE.parents[2] / "experiments" / "results"
OUT = HERE / "generated"
ALPHA = 0.05
PROPOSED_LABEL = "Hệ đề xuất"
CASE_MODEL = "Qwen/Qwen3.5-2B"

AGENTS = {  # id -> (display, macro code)
    "alignmentgraph-isd": (PROPOSED_LABEL, "AG"),
    "baseline": ("Baseline", "Base"),
    "react-isd": ("React-ADDIE", "React"),
    "addie-agent": ("ADDIE-Agent", "Addie"),
    "dick-carey-agent": ("Dick-Carey-Agent", "Dick"),
    "rpisd-agent": ("RPISD-Agent", "Rpisd"),
    "eduplanner": ("EduPlanner", "Edu"),
}
SCORES = {  # pooled key -> (mean field, sd field, macro code)
    "addie_median": ("mean_addie", "sd_addie_across_scenarios", "Addie"),
    "trajectory_score": ("mean_traj", "sd_traj_across_scenarios", "Traj"),
    "total_score": ("mean_total", "sd_total_across_scenarios", "Total"),
}
#: Element types counted for the case, in the order the stages write them.
CASE_TYPES = {"objective": "Obj", "module": "Mod", "assessment": "Task",
              "activity": "Act", "material": "Mat", "session_guide": "Sess"}
CORE = {"C2": "Two", "C3": "Three", "C4": "Four"}
#: The artifacts of stages 2-6 -- what a local revision could touch. The analysis
#: elements (gaps, topics, constraints, improvements) are left out of the count.
DESIGN_TYPES = {"objective", "module", "assessment", "activity", "media_selection",
                "material", "session_guide"}
#: Vietnamese number words for the small counts the prose writes out.
WORDS = {1: "một", 2: "hai", 3: "ba", 4: "bốn", 5: "năm", 6: "sáu", 7: "bảy", 8: "tám",
         9: "chín", 10: "mười"}


def word(n: int) -> str:
    return WORDS.get(n, str(n))

DASH = "--"


# ── formatting ──────────────────────────────────────────────────────────────
def ok(x) -> bool:
    return isinstance(x, (int, float)) and not (isinstance(x, float) and math.isnan(x))


def f1(x) -> str:
    return f"{x:.1f}" if ok(x) else DASH


def fp(p) -> str:
    """A p-value with its relation, so the prose writes ``$p$\\cmpXP``."""
    if not ok(p):
        return DASH
    return "${<}\\,0.001$" if p < 0.001 else f"${{=}}\\,{p:.3f}$"


def pct(x) -> str:
    return f"{100 * x:.0f}" if ok(x) else DASH


def ktok(x) -> str:
    return f"{x / 1000:.0f}" if ok(x) else DASH


def bold_best(cells: list[str], values: list) -> list[str]:
    vals = [v for v in values if ok(v)]
    if not vals:
        return cells
    best = max(vals)
    return [rf"\textbf{{{c}}}" if ok(v) and v == best else c for c, v in zip(cells, values)]


def star(cell: str, p) -> str:
    return cell + r"$^{*}$" if ok(p) and p < ALPHA else cell


class Macros:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def add(self, name: str, value: str) -> None:
        if not name.isalpha():
            raise ValueError(f"macro name must be letters only: {name}")
        self.lines.append(rf"\newcommand{{\{name}}}{{{value}}}")

    def write(self, path: Path) -> None:
        path.write_text("% Generated by make_tables.py — do not edit.\n"
                        + "\n".join(self.lines) + "\n", encoding="utf-8")


# ── the benchmark comparison ────────────────────────────────────────────────
def one_model(doc: dict) -> dict:
    models = doc.get("models") or []
    if len(models) != 1:
        raise SystemExit(f"expected exactly one model size, found {len(models)}")
    return models[0]


def comparison_rows(model: dict, score: str, policy: str) -> dict[str, dict]:
    rows = (model.get("comparisons", {}).get("by_score", {}).get(score, {})
            .get("policies", {}).get(policy, []))
    return {r["baseline"]: r for r in rows}


def judge_table(doc: dict, mac: Macros) -> str:
    cfg = doc["config"]
    proposed = cfg["proposed"]
    order = [proposed] + [b for b in cfg["baselines"] if b != proposed]
    model = one_model(doc)
    agents = model["agents"]
    n = model.get("n_scenarios_union")
    policy = model["comparisons"]["primary_policy"]
    tokens = doc.get("token_usage", {}).get("models", {}).get(model["label"], {})
    mac.add("NScen", str(n))

    cols: dict[str, list[str]] = {s: [] for s in SCORES}
    vals: dict[str, list] = {s: [] for s in SCORES}
    tok_cells, failed, tok_n = [], [], []
    better: dict[str, list[float]] = {}
    for a in order:
        st = agents.get(a, {})
        code = AGENTS.get(a, (a, a))[1]
        n_failed = st.get("n_scenarios_any_missing")
        if ok(n_failed) and n_failed:
            failed.append((a, n_failed))
        for s, (mf, sf, sc) in SCORES.items():
            m, sd = st.get(mf), st.get(sf)
            row = comparison_rows(model, s, policy).get(a, {})
            cell = f"{f1(m)}\\,$\\pm$\\,{f1(sd)}" if ok(m) else DASH
            cols[s].append(star(cell, row.get("p_holm")) if a != proposed else cell)
            vals[s].append(m)
            mac.add(f"cmp{code}{sc}", f1(m))
            mac.add(f"cmp{code}{sc}SD", f1(sd))
            if a != proposed:
                mac.add(f"cmp{code}{sc}Diff", f1(row.get("mean_diff")))
                mac.add(f"cmp{code}{sc}P", fp(row.get("p_holm")))
                lo, hi = (row.get("ci95") or [None, None])[:2]
                mac.add(f"cmp{code}{sc}CILo", f1(lo))
                mac.add(f"cmp{code}{sc}CIHi", f1(hi))
                if ok(row.get("p_holm")) and row["p_holm"] < ALPHA and ok(row.get("mean_diff")) \
                        and row["mean_diff"] > 0:
                    better.setdefault(s, []).append(row["p_holm"])
        t = tokens.get(a, {}).get("total_tokens", {}).get("mean")
        tn = tokens.get(a, {}).get("total_tokens", {}).get("n_scenarios")
        if ok(tn) and ok(n) and tn < n:
            tok_n.append((a, tn))
        secs = tokens.get(a, {}).get("execution_time_seconds", {}).get("mean")
        mac.add(f"cmp{code}Min", f"{secs / 60:.0f}" if ok(secs) else DASH)
        tok_cells.append(ktok(t))
        mac.add(f"cmp{code}Tok", ktok(t))
        calls = tokens.get(a, {}).get("llm_calls", {}).get("mean")
        mac.add(f"cmp{code}Calls", f"{calls:.0f}" if ok(calls) else DASH)
    for s in SCORES:
        cols[s] = bold_best(cols[s], vals[s])
    # the largest Holm p among the baselines the proposed system scores above, per score
    for s, (_, _, sc) in SCORES.items():
        mac.add(f"cmpMaxP{sc}Better", fp(max(better[s])) if better.get(s) else DASH)
    ag = tokens.get(proposed, {}).get("total_tokens", {}).get("mean")
    re_ = tokens.get("react-isd", {}).get("total_tokens", {}).get("mean")
    if ok(ag) and ok(re_) and re_:
        mac.add("cmpTokRatioReact", f"{ag / re_:.0f}")

    body = []
    for i, a in enumerate(order):
        cells = [cols[s][i] for s in SCORES] + [tok_cells[i]]
        body.append(f"    {AGENTS.get(a, (a, a))[0]} & " + " & ".join(cells) + r" \\")
    notes = [r"$^{*}$ khác có ý nghĩa so với hệ đề xuất (Wilcoxon theo cặp, Holm trong từng "
             r"điểm, $p<0.05$)."]
    if tok_n:
        notes.append("Token trung bình trên các kịch bản có số liệu: "
                     + ", ".join(f"{AGENTS.get(a, (a,))[0]} {k}" for a, k in tok_n) + ".")
    if failed:
        notes.append("Kịch bản không có đầu ra chấm được, tính 0 điểm: "
                     + ", ".join(f"{AGENTS.get(a, (a,))[0]} {k}" for a, k in failed) + ".")
    return "\n".join([
        r"\begin{table}[t]",
        rf"  \caption{{Điểm LLM judge trên ISD-Agent-Bench (trung bình $\pm$ độ lệch chuẩn qua "
        rf"{n} kịch bản) và token mỗi kịch bản}}",
        r"  \label{tab:judge}",
        r"  \centering",
        r"  \footnotesize",
        r"  \setlength{\tabcolsep}{2.5pt}",
        r"  \begin{tabular}{@{}lcccc@{}}",
        r"    \toprule",
        r"    Hệ & ADDIE $\uparrow$ & Trajectory $\uparrow$ & Total $\uparrow$ "
        r"& Token (k) $\downarrow$ \\",
        r"    \midrule",
        *body,
        r"    \bottomrule",
        r"  \end{tabular}",
        r"  \par\vspace{2pt}",
        r"  {\scriptsize\raggedright " + r"\\ ".join(notes) + r"\par}",
        r"\end{table}",
        "",
    ])


def judge_spread(doc: dict, mac: Macros) -> None:
    """Mean SD between the three LLM judges' ADDIE scores over every judged output."""
    root = Path(one_model(doc)["run_dirs"][0])
    spreads: list[float] = []
    for report in sorted(root.glob("*/*/comparison_report.json")):
        rows = json.loads(report.read_text(encoding="utf-8"))["comparison"]["rankings"]
        for row in rows:
            judges = row["judges"]
            if isinstance(judges, str):
                judges = ast.literal_eval(judges)
            scores = [j["addie_score"] for j in judges
                      if ok(j.get("addie_score")) and not j.get("error")]
            if len(scores) >= 2:
                spreads.append(statistics.stdev(scores))
    mac.add("JudgeSD", f1(statistics.mean(spreads)) if spreads else DASH)


# ── the deployment case (one web-app run) ───────────────────────────────────
def case_macros(run: Path, mac: Macros) -> None:
    meta = json.loads((run / "metadata.json").read_text(encoding="utf-8"))
    model = (meta.get("llm") or {}).get("model") or (meta.get("llm") or {}).get("model_name")
    if model and model != CASE_MODEL:
        raise SystemExit(f"{run}: the case was run on {model!r}, expected {CASE_MODEL!r}")
    graph = json.loads((run / "graph.json").read_text(encoding="utf-8"))
    ledger = json.loads((run / "violations.json").read_text(encoding="utf-8"))
    addie = json.loads((run / "addie_output.json").read_text(encoding="utf-8"))

    counts = {t: 0 for t in CASE_TYPES}
    for node in graph["nodes"]:
        if node.get("type") in counts:
            counts[node["type"]] += 1
    for t, code in CASE_TYPES.items():
        mac.add(f"case{code}", str(counts[t]))
    tasks = (addie.get("development") or {}).get("assessment_tools") or []
    mac.add("caseItem", str(sum(len(t.get("items") or []) for t in tasks)))

    cov = graph.get("relation_coverage") or {}
    for rid, code in CORE.items():
        mac.add(f"caseCov{code}", pct((cov.get(rid) or {}).get("coverage")))
    legs = graph.get("objective_alignment") or {}
    closed = sum(1 for o in legs.values()
                 if all(leg.get("ok") for leg in o.get("legs", [])) and o.get("legs"))
    mac.add("caseClosed", str(closed))

    # The ledger must agree with the final graph: a finding the graph still flags on
    # its node cannot be counted repaired (case/reconcile_ledger.py corrects the run).
    flagged = graph.get("node_violations") or {}
    for f in ledger:
        if f.get("outcome") != "open" and f.get("type") in (flagged.get(f.get("node_id")) or []):
            raise SystemExit(f"{run}: ledger says {f['key']} is {f['outcome']} but the final "
                             "graph still flags it; run case/reconcile_ledger.py first")
    outcomes = {"repaired_by_agent": "Agent", "repaired_by_harness": "Harness", "open": "Open"}
    mac.add("caseViol", str(len(ledger)))
    for outcome, code in outcomes.items():
        mac.add(f"caseViol{code}", str(sum(1 for f in ledger if f.get("outcome") == outcome)))

    open_types = [f.get("type") for f in ledger if f.get("outcome") == "open"]
    mac.add("caseOverrunMods", word(open_types.count("time_budget")))
    mac.add("caseMediaMismatch", word(open_types.count("P6")))

    local_scope(graph, ledger, mac)
    figure_numbers(graph, mac)
    diagnostic_only(graph, addie, mac)

    events = (json.loads((run / "trajectory.json").read_text(encoding="utf-8"))
              .get("events") or [])
    stamps = [e["timestamp"] for e in events if e.get("timestamp")]
    if stamps:
        from datetime import datetime
        span = datetime.fromisoformat(max(stamps)) - datetime.fromisoformat(min(stamps))
        mac.add("caseMin", f"{span.total_seconds() / 60:.0f}")

    usage = meta.get("token_usage") or {}
    mac.add("caseTok", ktok(usage.get("total_tokens")))
    mac.add("caseCalls", str(usage.get("llm_calls", DASH)))


def local_scope(graph: dict, ledger: list, mac: Macros) -> None:
    """What a local fix of the open Bloom-mismatch finding would touch, read off the graph.

    The candidates to rewrite are the activities whose C3 edge the check flagged;
    the artifacts to review with them are the design artifacts ONE edge away
    (structural/scaffolding edges and section nodes excluded). Counted over the
    design artifacts of stages 2-6 only. This is the one-edge neighbourhood the
    graph identifies, not a propagation analysis -- and the revision loop itself
    is not implemented."""
    design = {n["id"] for n in graph["nodes"]
              if n.get("kind") == "element" and n.get("type") in DESIGN_TYPES}
    rewrite = {e["target"] for e in graph["edges"]
               if e.get("invalid") and str(e.get("type", "")).startswith("C3")}
    finding = next((f for f in ledger if f.get("type") == "bloom_mismatch_activity"), None)
    if not rewrite or finding is None:
        return
    touched = set(rewrite)
    for e in graph["edges"]:
        if e.get("tier") == "structural" or e.get("layer") == "scaffolding":
            continue
        for a, b in ((e["source"], e["target"]), (e["target"], e["source"])):
            if a in rewrite and b in design:
                touched.add(b)
    mac.add("caseDesign", str(len(design)))
    mac.add("caseLocalRewrite", word(len(rewrite)))
    mac.add("caseLocalCheck", str(len(touched - rewrite)))
    mac.add("caseLocalOutside", str(len(design - touched)))
    mac.add("caseLocalObjective", str(finding.get("metadata", {}).get("lo_id", "")).replace("_", "-"))


def _edges(graph: dict, node: str, rel: str, end: str) -> list[str]:
    """Ids at the other end of ``rel`` edges, where ``node`` is the edge's ``end``."""
    other = "target" if end == "source" else "source"
    return [e[other] for e in graph["edges"]
            if e.get(end) == node and str(e.get("type", "")).startswith(rel + "-")]


def figure_numbers(graph: dict, mac: Macros) -> None:
    """The counts Hình 3 shows for its three artifacts, read off the graph."""
    nodes = {n["id"]: n for n in graph["nodes"]}
    mac.add("caseMatSessions", word(len(_edges(graph, "material:MAT-0101", "P11", "target"))))
    dur = str((nodes.get("activity:TLA-0102") or {}).get("data", {}).get("duration", ""))
    mac.add("caseActMinutes", dur.split()[0] if dur else DASH)
    mac.add("caseTaskObjs", word(len(_edges(graph, "assessment:AT-02", "C2", "target"))))
    mac.add("caseTaskActs", word(len(_edges(graph, "assessment:AT-02", "C4", "target"))))


def diagnostic_only(graph: dict, addie: dict, mac: Macros) -> None:
    """Objectives whose only C2 edges end on diagnostic tasks, and the tasks' total weight."""
    tasks = {f"assessment:{t.get('id')}": t
             for t in (addie.get("development") or {}).get("assessment_tools") or []}
    objs = [n["id"] for n in graph["nodes"] if n.get("type") == "objective"]
    only = [o for o in objs
            if (ends := _edges(graph, o, "C2", "source"))
            and all((tasks.get(d) or {}).get("timing") == "diagnostic" for d in ends)]
    mac.add("caseDiagOnly", word(len(only)))
    mac.add("caseDiagOnlyIds", " và ".join(o.split(":", 1)[1] for o in only))
    diag = [int(t.get("weight_percent") or 0) for t in tasks.values() if t.get("timing") == "diagnostic"]
    mac.add("caseDiagWeight", str(sum(diag)) if diag else DASH)
    mac.add("caseWeight", str(sum(int(t.get("weight_percent") or 0) for t in tasks.values())))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--comparison", type=Path, default=RESULTS / "pooled_comparison.json")
    ap.add_argument("--case-dir", type=Path, default=HERE / "case" / "run",
                    help="the web-app run dir of the deployment case (default: the copy "
                         "kept beside the paper, case/run/)")
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()

    args.out.mkdir(parents=True, exist_ok=True)
    mac = Macros()
    if args.comparison.exists():
        doc = json.loads(args.comparison.read_text(encoding="utf-8"))
        (args.out / "tab_judge.tex").write_text(judge_table(doc, mac), encoding="utf-8")
        judge_spread(doc, mac)
        print("wrote", args.out / "tab_judge.tex")
    else:
        print(f"skip the judge table: {args.comparison} not found")
    if args.case_dir and (args.case_dir / "graph.json").exists():
        case_macros(args.case_dir, mac)
        print("read the case from", args.case_dir)
    else:
        print("skip the case macros: no --case-dir")
    mac.write(args.out / "macros.tex")
    print("wrote", args.out / "macros.tex")


if __name__ == "__main__":
    main()
